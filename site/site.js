const titles = {ja: "StagePane — 見せたいものだけ、ひとつのステージへ。", en: "StagePane — A clean stage for everything you share."};
function setLanguage(language, updateURL = false) {
  const lang = language === 'en' ? 'en' : 'ja';
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const entry = translations[element.dataset.i18n];
    for (const [attribute, value] of Object.entries(entry)) {
      if (attribute === 'html') element.innerHTML = value[lang];
      else element.setAttribute(attribute, value[lang]);
    }
  });
  document.documentElement.lang = lang;
  document.title = titles[lang];
  document.querySelectorAll('[data-language]').forEach(link => {
    link.href = '?lang=' + link.dataset.language + location.hash;
  });
  if (updateURL) {
    const url = new URL(location.href);
    url.searchParams.set('lang', lang);
    history.pushState(null, '', url);
  }
}
document.addEventListener('click', event => {
  const language = event.target.closest('[data-language]');
  if (language) { event.preventDefault(); setLanguage(language.dataset.language, true); }
  const anchor = event.target.closest('a[href^="#"]');
  if (anchor) document.querySelectorAll('.mobile-menu[open]').forEach(menu => menu.removeAttribute('open'));
});
